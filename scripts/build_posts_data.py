"""Build js/kallmann-posts-data.js from the health-social-media-viz project's index.html.

That page embeds every r/kallmann_syndrome post (date, poster type, post type, title, snippet,
score, comment count, Reddit link) in a `const DATA = {...};` line. This copies the posts, plus
the category orders and the covered date range, into a script the dashboard loads.

Usage:
    python3 scripts/build_posts_data.py /path/to/health-social-media-viz/index.html
"""

import calendar
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = ROOT / "js" / "kallmann-posts-data.js"


def load_viz_data(viz_html):
    for line in Path(viz_html).read_text(encoding="utf-8").splitlines():
        if line.startswith("const DATA = "):
            return json.loads(line[len("const DATA = "):].rstrip(";"))
    sys.exit(f"Could not find 'const DATA = ...' in {viz_html}")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    viz = load_viz_data(sys.argv[1])

    posts = sorted(
        (
            {
                "date": p["date"],
                "who": p["who"],
                "what": p["what"],
                "title": p["title"],
                "snippet": p["snippet"],
                "score": p["score"],
                "comments": p["num_comments"],
                "url": p["permalink"],
            }
            for p in viz["posts"]
        ),
        key=lambda p: p["date"],
    )

    # The covered period runs from the first day of the first month to the last day of the last month.
    first_month, last_month = viz["months"][0]["month"], viz["months"][-1]["month"]
    year, month = map(int, last_month.split("-"))
    start = f"{first_month}-01"
    end = f"{last_month}-{calendar.monthrange(year, month)[1]:02d}"
    assert all(start <= p["date"] <= end for p in posts), "post dates fall outside the monthly range"
    assert len(posts) == sum(m["count"] for m in viz["months"]), "post count does not match monthly totals"

    body = ",\n".join("  " + json.dumps(p, ensure_ascii=False) for p in posts)
    OUT_PATH.write_text(
        "/**\n"
        f" * r/kallmann_syndrome posts ({start} to {end}, {len(posts)} posts), oldest first.\n"
        " * Generated by scripts/build_posts_data.py from the DATA object embedded in the\n"
        " * health-social-media-viz project's index.html. Do not edit by hand: re-run the script.\n"
        " */\n"
        "/* eslint-disable no-unused-vars */\n"
        f"const KALLMANN_POSTS_RANGE = {json.dumps({'start': start, 'end': end})};\n"
        f"const KALLMANN_WHO_ORDER = {json.dumps(viz['whoOrder'])};\n"
        f"const KALLMANN_WHAT_ORDER = {json.dumps(viz['whatOrder'])};\n"
        f"const KALLMANN_POSTS = [\n{body}\n];\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(posts)} posts ({start} to {end}) to {OUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
